#switch value of to integers.
n1=20
n2=30
print(f"before swapping the value n1:{n1}")
print(f"before swapping the value n2:{n2}")
x=n1 
n1=n2 
n2=x 
print(f"after swapping the value n1:{n1}")
print(f"after swapping the value n2:{n2}")         

#switch values of two strings(characters)
